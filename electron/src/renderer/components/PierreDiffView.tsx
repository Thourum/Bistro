/** A flattened, ordered annotation entry used for j/k keyboard navigation. */
interface AnnotationEntry {
  /** Unique key = thread id. */
  key: string;
  threadId: string;
  /** Index of the owning file in the `files` array — for scroll-to-file. */
  fileIndex: number;
  fileId: string;
  line: number;
}

function sameIds(left: string[], right: string[]): boolean {
  if (left.length !== right.length) return false;
  return left.every((value, index) => value === right[index]);
}

export interface PierreDiffViewProps {
  /** Full unified-diff string (`diff --git …` separated). */
  diff: string;
  /** Current theme; currently unused but we thread it through so the
   *  component can re-render when the user flips modes. */
  theme: AppSettings['appearance']['theme'];
  /** Optional find query used to narrow the file list. Diff-canvas
   *  find-in-content is deferred to a later pass. */
  findQuery?: string;
  /**
   * Canonical file key (from `?file` search param) used to pre-select a file
   * when navigating directly to the diff route.  If empty or not found,
   * falls back to the first file.
   */
  selectedFileKey?: string;
  /**
   * Called once when the parsed file list changes, with the full list of
   * canonical keys in order.  `DiffPage` uses this to populate
   * `store.diffFileKeys` so n/p keybindings can navigate by key.
   */
  onFilesResolved?: (canonicalKeys: string[]) => void;
  /**
   * Review threads for the PR. When provided together with `comments`,
   * inline annotation cards are rendered in the diff canvas at each thread's
   * line position (additions side).
   */
  threads?: ReviewThread[];
  /**
   * All PR comments. Joined to `threads` by `thread_id` to build per-thread
   * discussion cards.
   */
  comments?: Comment[];
}

interface ParsedFile {
  /** A stable key for React. */
  id: string;
  /** `a/foo.ts` → `foo.ts` (best-effort). */
  path: string;
  /**
   * DiffFileIdentity fields (with git `a/`/`b/` prefixes or `/dev/null`).
   * Used by diffFileKey.ts (`buildFileKeys`, `findFileByKey`) — the SINGLE
   * canonical key authority.  All key generation/resolution flows
   * through diffFileKey.ts, not a private clone.
   */
  oldFile: string;
  newFile: string;
  /**
   * Canonical key for the `?file` search param — generated by
   * `buildFileKeys` from diffFileKey.ts.
   */
  canonicalKey: string;
  /** Extracted language tag, e.g. `TS`, `RS`. */
  lang: string;
  /** Added LOC count. */
  additions: number;
  /** Removed LOC count. */
  deletions: number;
  /** The per-file unified-diff slice. */
  patch: string;
  /** Total lines in the patch — used to estimate virtual row heights. */
  lineCount: number;
}

/**
 * `PierreDiffView` — wraps `@pierre/diffs/react` to render a multi-file
 * unified-diff payload using the 25/75 split layout from
 * `diff_view_minimal_light/code.html`.
 *
 * Inline thread annotations are rendered via `PatchDiff`'s `lineAnnotations` /
 * `renderAnnotation` API. Each `ReviewThread` whose `file_path` matches the
 * current file is placed on the `additions` side at `thread.line`. Comments
 * whose `thread_id` matches the thread are joined and rendered in a compact
 * card.
 */
export function PierreDiffView({
  diff,
  theme,
  findQuery = '',
  selectedFileKey,
  onFilesResolved,
  threads = [],
  comments = [],
}: PierreDiffViewProps) {
  const files = useMemo(() => splitUnifiedDiff(diff), [diff]);
  const [activeId, setActiveId] = useState<string | null>(files[0]?.id ?? null);
  // Registered by DiffCanvas so nav clicks can jump the virtualized list.
  const scrollToFileRef = useRef<(id: string) => void>(() => undefined);
  const selectedFileIndex = useStore(appStore, (s) => s.selectedFileIndex);

  // ── Inline annotation hotkey state ───────────────────────────────
  // Centralized keybindings own j/k/Enter/Escape. PierreDiffView publishes the
  // ordered inline-thread ids and renders the selected/replying state.
  const activeAnnotationKey = useStore(
    appStore,
    (s) => s.activeInlineCommentThreadId,
  );
  const replyingToThreadId = useStore(
    appStore,
    (s) => s.replyingInlineCommentThreadId,
  );

  /**
   * Flat ordered annotation list: file order → line number → thread id.
   * Used by j/k navigation to move between all threads in the diff.
   */
  const orderedAnnotations = useMemo<AnnotationEntry[]>(() => {
    const entries: AnnotationEntry[] = [];
    files.forEach((file, fileIndex) => {
      const fileThreads = threads
        .filter((t) => t.file_path === file.path)
        .sort((a, b) => a.line - b.line || a.id.localeCompare(b.id));
      for (const t of fileThreads) {
        entries.push({
          key: t.id,
          threadId: t.id,
          fileIndex,
          fileId: file.id,
          line: t.line,
        });
      }
    });
    return entries;
  }, [files, threads]);

  // Publish ordered annotation ids to the central hotkey layer. When the list
  // shrinks, clear stale selected/replying ids.
  useEffect(() => {
    const ids = orderedAnnotations.map((entry) => entry.key);
    appStore.setState((s) => {
      const activeStillValid =
        s.activeInlineCommentThreadId !== null &&
        ids.includes(s.activeInlineCommentThreadId);
      const replyingStillValid =
        s.replyingInlineCommentThreadId !== null &&
        ids.includes(s.replyingInlineCommentThreadId);
      if (
        sameIds(s.inlineCommentThreadIds, ids) &&
        (s.activeInlineCommentThreadId === null || activeStillValid) &&
        (s.replyingInlineCommentThreadId === null || replyingStillValid)
      ) {
        return s;
      }
      return {
        ...s,
        inlineCommentThreadIds: ids,
        activeInlineCommentThreadId: activeStillValid
          ? s.activeInlineCommentThreadId
          : null,
        replyingInlineCommentThreadId: replyingStillValid
          ? s.replyingInlineCommentThreadId
          : null,
      };
    });
  }, [orderedAnnotations]);

  useEffect(() => {
    return () => {
      appStore.setState((s) => ({
        ...s,
        inlineCommentThreadIds: [],
        activeInlineCommentThreadId: null,
        replyingInlineCommentThreadId: null,
      }));
    };
  }, []);

  // Scroll the active annotation card into view whenever it changes.
  useEffect(() => {
    if (activeAnnotationKey === null) return;
    const entry = orderedAnnotations.find((e) => e.key === activeAnnotationKey);
    if (entry === undefined) return;
    // First, make sure the file containing the annotation is scrolled into view.
    scrollToFileRef.current(entry.fileId);
    // Then scroll the card itself into view. The DOM element may not be mounted
    // yet if the virtualizer hasn't caught up, so we defer one frame.
    const raf = requestAnimationFrame(() => {
      const el = document.querySelector<HTMLElement>(
        `[data-annotation-key="${CSS.escape(activeAnnotationKey)}"]`,
      );
      el?.scrollIntoView({ block: 'nearest', behavior: 'smooth' });
    });
    return () => cancelAnimationFrame(raf);
  }, [activeAnnotationKey, orderedAnnotations]);

  useEffect(() => {
    if (files.length === 0) {
      setActiveId(null);
      return;
    }
    if (activeId === null || !files.some((f) => f.id === activeId)) {
      setActiveId(files[0]?.id ?? null);
    }
  }, [files, activeId]);

  // Notify DiffPage (and the store via onFilesResolved) whenever the parsed
  // file list changes, so keybindings have an up-to-date canonical key list.
  // useLayoutEffect so diffFileKeys commits before the next paint / input.
  useLayoutEffect(() => {
    if (files.length === 0) {
      onFilesResolved?.([]);
      return;
    }
    onFilesResolved?.(files.map((f) => f.canonicalKey));
  }, [files, onFilesResolved]);

  // When selectedFileKey changes (i.e. ?file param changed), activate
  // the matching file via findFileByKey (diffFileKey.ts). Falls back to files[0].
  useEffect(() => {
    if (files.length === 0) return;
    if (selectedFileKey === undefined) return;
    // Resolve via the single canonical authority (findFileByKey).
    // Empty string means no ?file param — fall back to the first file.
    const match =
      (selectedFileKey !== ''
        ? findFileByKey(files, selectedFileKey)
        : undefined) ?? files[0];
    if (match !== undefined && match.id !== activeId) {
      setActiveId(match.id);
      scrollToFileRef.current(match.id);
      // Sync the store cursor so n/p keybindings stay relative to what's visible.
      const idx = files.indexOf(match);
      if (idx >= 0 && appStore.state.selectedFileIndex !== idx) {
        appStore.setState((s) => ({ ...s, selectedFileIndex: idx }));
      }
    }
    // activeId intentionally omitted — same reasoning as the selectedFileIndex effect.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [selectedFileKey, files]);

  // The n/p keybindings drive store.selectedFileIndex; follow it here.
  useEffect(() => {
    if (files.length === 0) return;
    const clamped = Math.min(Math.max(selectedFileIndex, 0), files.length - 1);
    if (clamped !== selectedFileIndex) {
      appStore.setState((s) => ({ ...s, selectedFileIndex: clamped }));
      return;
    }
    const file = files[clamped];
    if (file !== undefined && file.id !== activeId) {
      setActiveId(file.id);
      scrollToFileRef.current(file.id);
    }
    // activeId intentionally omitted: scroll-driven highlight changes must
    // not yank the viewport back to the store-selected file.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [selectedFileIndex, files]);

  // Keep the store index in sync when scrolling changes the active file, so
  // the next n/p press moves relative to what the user actually sees.
  const handleActiveChange = (id: string): void => {
    setActiveId(id);
    const idx = files.findIndex((f) => f.id === id);
    if (idx >= 0 && appStore.state.selectedFileIndex !== idx) {
      appStore.setState((s) => ({ ...s, selectedFileIndex: idx }));
    }
  };

  const filtered = useMemo(() => {
    const q = findQuery.trim().toLowerCase();
    if (q === '') return files;
    return files.filter((f) => f.path.toLowerCase().includes(q));
  }, [files, findQuery]);

  // Group comments by thread_id for O(1) lookup in DiffCanvas.
  const commentsByThread = useMemo(() => {
    const map = new Map<string, Comment[]>();
    for (const c of comments) {
      if (c.thread_id === undefined) continue;
      const bucket = map.get(c.thread_id);
      if (bucket === undefined) map.set(c.thread_id, [c]);
      else bucket.push(c);
    }
    return map;
  }, [comments]);

  if (files.length === 0) {
    return (
      <div className="w-full h-full flex items-center justify-center text-outline font-mono text-xs uppercase tracking-widest">
        No changes
      </div>
    );
  }

  return (
    <div className="w-full h-full flex overflow-hidden">
      <FileNav
        files={filtered}
        activeId={activeId}
        onSelect={(id) => {
          setActiveId(id);
          scrollToFileRef.current(id);
        }}
        totalCount={files.length}
      />
      <DiffCanvas
        files={files}
        activeId={activeId}
        theme={theme}
        onActiveChange={handleActiveChange}
        registerScrollTo={(fn) => {
          scrollToFileRef.current = fn;
        }}
        threads={threads}
        commentsByThread={commentsByThread}
        activeAnnotationKey={activeAnnotationKey}
        replyingToThreadId={replyingToThreadId}
        onAnnotationActivate={(threadId) => {
          appStore.setState((s) => ({
            ...s,
            activeInlineCommentThreadId: threadId,
          }));
        }}
        onReplyClose={() => {
          appStore.setState((s) => ({
            ...s,
            replyingInlineCommentThreadId: null,
          }));
        }}
      />
    </div>
  );
}

interface FileNavProps {
  files: ParsedFile[];
  activeId: string | null;
  onSelect: (id: string) => void;
  totalCount: number;
}

function FileNav({ files, activeId, onSelect, totalCount }: FileNavProps) {
  return (
    <aside className="w-1/4 min-w-[220px] bg-surface-container-low border-r border-outline-variant/20 overflow-y-auto">
      <div className="p-4">
        <h3 className="font-mono text-[10px] font-bold text-outline tracking-widest uppercase mb-4">
          Files Changed ({totalCount.toString().padStart(2, '0')})
        </h3>
        <nav className="space-y-1">
          {files.map((f) => {
            const isActive = f.id === activeId;
            return (
              <button
                key={f.id}
                type="button"
                onClick={() => onSelect(f.id)}
                className={`w-full flex items-center gap-2 px-2 py-1.5 text-left transition-colors ${
                  isActive
                    ? 'bg-surface-container-lowest text-primary border-l-2 border-primary'
                    : 'hover:bg-surface-container-highest/50 text-on-surface border-l-2 border-transparent'
                }`}
              >
                <span
                  className={`material-symbols-outlined text-[16px] ${
                    isActive ? 'text-primary' : 'text-outline'
                  }`}
                >
                  description
                </span>
                <span className="font-mono text-[11px] truncate flex-1">
                  {f.path}
                </span>
                <span className="font-mono text-[9px] text-outline shrink-0">
                  +{f.additions}/-{f.deletions}
                </span>
              </button>
            );
          })}
        </nav>
      </div>
    </aside>
  );
}

interface DiffCanvasProps {
  files: ParsedFile[];
  activeId: string | null;
  theme: AppSettings['appearance']['theme'];
  onActiveChange: (id: string) => void;
  registerScrollTo: (fn: (id: string) => void) => void;
  threads: ReviewThread[];
  commentsByThread: Map<string, Comment[]>;
  activeAnnotationKey: string | null;
  replyingToThreadId: string | null;
  onAnnotationActivate: (key: string) => void;
  onReplyClose: () => void;
}

/** Estimated rendered height of one diff line, used until measurement. */
const ESTIMATED_LINE_HEIGHT = 20;
/** Per-file chrome: sticky header plus borders. */
const FILE_HEADER_HEIGHT = 40;

/**
 * Virtualized diff canvas: only the file blocks near the viewport are
 * mounted, so 100+ file diffs don't pay the DOM cost of every `PatchDiff`.
 * Rows are positioned with `top` (not `transform`) so the per-file sticky
 * headers keep sticking to the scroll viewport.
 */
function DiffCanvas({
  files,
  activeId,
  theme: _theme,
  onActiveChange,
  registerScrollTo,
  threads,
  commentsByThread,
  activeAnnotationKey,
  replyingToThreadId,
  onAnnotationActivate,
  onReplyClose,
}: DiffCanvasProps) {
  const scrollRef = useRef<HTMLElement>(null);

  const virtualizer = useVirtualizer({
    count: files.length,
    getScrollElement: () => scrollRef.current,
    estimateSize: (index) => {
      const file = files[index];
      if (file === undefined) return FILE_HEADER_HEIGHT;
      return FILE_HEADER_HEIGHT + file.lineCount * ESTIMATED_LINE_HEIGHT;
    },
    overscan: 2,
    getItemKey: (index) => files[index]?.id ?? index,
  });

  useEffect(() => {
    registerScrollTo((id: string) => {
      const idx = files.findIndex((f) => f.id === id);
      if (idx >= 0) {
        virtualizer.scrollToIndex(idx, { align: 'start' });
      }
    });
  }, [files, virtualizer, registerScrollTo]);

  const virtualItems = virtualizer.getVirtualItems();

  // The topmost visible file drives the nav highlight. Scrolling never
  // scrolls back (no scroll-jacking) — only nav clicks call scrollToIndex.
  const scrollOffset = virtualizer.scrollOffset ?? 0;
  const firstVisibleIndex =
    virtualItems.find((v) => v.end > scrollOffset + 1)?.index ?? -1;

  useEffect(() => {
    if (firstVisibleIndex < 0) return;
    const file = files[firstVisibleIndex];
    if (file !== undefined && file.id !== activeId) {
      onActiveChange(file.id);
    }
  }, [firstVisibleIndex, files, activeId, onActiveChange]);

  return (
    <section
      ref={scrollRef}
      data-diff-viewport
      className="flex-1 bg-surface-container-lowest overflow-auto relative"
    >
      <div
        className="relative w-full"
        style={{ height: virtualizer.getTotalSize() }}
      >
        {virtualItems.map((virtualRow) => {
          const file = files[virtualRow.index];
          if (file === undefined) return null;
          // Build per-file line annotations from threads whose file_path
          // matches this file. Placed on the additions side (new-file line
          // numbers) — old-side line info is not yet available.
          const fileAnnotations: DiffLineAnnotation<ReviewThread>[] = threads
            .filter((t) => t.file_path === file.path)
            .map((t) => ({
              side: 'additions' as const,
              lineNumber: t.line,
              metadata: t,
            }));

          return (
            <div
              key={virtualRow.key}
              ref={virtualizer.measureElement}
              data-index={virtualRow.index}
              data-file-id={file.id}
              className="absolute left-0 w-full border-b border-outline-variant/10"
              style={{ top: virtualRow.start }}
            >
              <div className="sticky top-0 z-10 bg-surface-container-lowest border-b border-outline-variant/10 px-4 py-2 flex items-center justify-between">
                <div className="flex items-center gap-2 min-w-0">
                  <span className="text-outline font-mono text-[11px] truncate">
                    {file.path}
                  </span>
                  <span className="bg-surface-container px-2 py-0.5 text-[10px] text-outline uppercase font-mono shrink-0">
                    {file.lang}
                  </span>
                </div>
                <div className="flex gap-4 font-mono text-[11px] font-bold shrink-0">
                  <span className="text-primary">+{file.additions}</span>
                  <span className="text-error">-{file.deletions}</span>
                </div>
              </div>
              <PatchDiff
                options={{
                  theme: `pierre-${_theme}`,
                }}
                patch={file.patch}
                disableWorkerPool
                className="block w-full"
                {...(fileAnnotations.length > 0
                  ? {
                      lineAnnotations: fileAnnotations,
                      renderAnnotation: (
                        annotation: DiffLineAnnotation<ReviewThread>,
                      ) => {
                        const tid = annotation.metadata?.id;
                        return (
                          <ThreadAnnotationCard
                            thread={annotation.metadata}
                            comments={
                              tid !== undefined
                                ? (commentsByThread.get(tid) ?? [])
                                : []
                            }
                            isActive={tid === activeAnnotationKey}
                            isReplying={tid === replyingToThreadId}
                            {...(tid !== undefined
                              ? {
                                  onActivate: () => onAnnotationActivate(tid),
                                }
                              : {})}
                            onReplyClose={onReplyClose}
                          />
                        );
                      },
                    }
                  : {})}
              />
            </div>
          );
        })}
      </div>
    </section>
  );
}

