import { buildFileKeys, type DiffFileIdentity } from '../../utils/diffFileKey';

export interface ParsedDiffFile {
  /** A stable key for React. */
  id: string;
  /** `a/foo.ts` → `foo.ts` (best-effort). */
  path: string;
  /**
   * DiffFileIdentity fields (with git `a/`/`b/` prefixes or `/dev/null`).
   * Used by diffFileKey.ts (`buildFileKeys`, `findFileByKey`) — the SINGLE
   * canonical key authority.  All key generation/resolution flows
   * through diffFileKey.ts, not a private clone.
   */
  oldFile: string;
  newFile: string;
  /**
   * Canonical key for the `?file` search param — generated by
   * `buildFileKeys` from diffFileKey.ts.
   */
  canonicalKey: string;
  /** Extracted language tag, e.g. `TS`, `RS`. */
  lang: string;
  /** Added LOC count. */
  additions: number;
  /** Removed LOC count. */
  deletions: number;
  /** The per-file unified-diff slice. */
  patch: string;
  /** Total lines in the patch — used to estimate virtual row heights. */
  lineCount: number;
}

/**
 * Extract `DiffFileIdentity` (oldFile / newFile with git `a/`/`b/` prefixes
 * or `/dev/null`) from a single-file patch chunk.
 *
 * Used to feed `buildFileKeys` / `findFileByKey` from diffFileKey.ts — the
 * single canonical key authority for `?file` param generation and resolution.
 * Handles: normal modify, rename (old≠new), deletion (new=/dev/null),
 * addition (old=/dev/null), paths with spaces (quoted git format).
 */
export function extractFileIdentity(patch: string): DiffFileIdentity {
  let oldFile = '/dev/null';
  let newFile = '/dev/null';

  // Quoted form: diff --git "a/..." "b/..."
  const quotedMatch = /^diff --git "a\/(.+)" "b\/(.+)"/m.exec(patch);
  if (quotedMatch !== null) {
    oldFile = `a/${quotedMatch[1] ?? ''}`;
    newFile = `b/${quotedMatch[2] ?? ''}`;
  } else {
    // Unquoted form: diff --git a/<oldPath> b/<newPath>
    const headerMatch = /^diff --git a\/.+ b\/.+$/m.exec(patch);
    if (headerMatch !== null) {
      const body = headerMatch[0].slice('diff --git '.length);
      const bIdx = body.lastIndexOf(' b/');
      if (bIdx !== -1) {
        oldFile = `a/${body.slice(2, bIdx)}`; // strip leading "a/"
        newFile = `b/${body.slice(bIdx + 3)}`; // after " b/"
      }
    }
  }

  // Override with /dev/null when the unified-diff +++ / --- lines say so.
  // This detects actual deletions (new=/dev/null) and additions (old=/dev/null)
  // even when the diff --git header shows the same path on both sides.
  const plusLine = /^\+\+\+ (.+)$/m.exec(patch)?.[1];
  const minusLine = /^--- (.+)$/m.exec(patch)?.[1];
  if (plusLine === '/dev/null') newFile = '/dev/null';
  if (minusLine === '/dev/null') oldFile = '/dev/null';

  return { oldFile, newFile };
}

/**
 * Split a multi-file unified diff into per-file entries keyed by path.
 *
 * Handles the standard `diff --git a/foo b/foo` preamble. If the payload does
 * not have `diff --git` headers (e.g. the server returned a plain patch), we
 * fall back to `^diff ` or `^---` separators so the library can still try to
 * render something sensible.
 */
export function splitUnifiedDiff(raw: string): ParsedDiffFile[] {
  if (raw.trim().length === 0) return [];

  if (!/^diff --git /m.test(raw)) {
    const { additions, deletions } = countChanges(raw);
    // Non-git diff: treat as a single unnamed file.
    const identity: DiffFileIdentity = { oldFile: '', newFile: 'patch' };
    const [canonicalKey] = buildFileKeys([identity]);
    if (canonicalKey === undefined) return [];
    return [
      {
        id: 'patch-0',
        path: 'patch',
        oldFile: identity.oldFile,
        newFile: identity.newFile,
        canonicalKey,
        lang: 'patch',
        additions,
        deletions,
        patch: raw,
        lineCount: countLines(raw),
      },
    ];
  }

  const lines = raw.split('\n');
  const chunks: string[] = [];
  let currentChunk: string[] = [];
  for (const line of lines) {
    if (line.startsWith('diff --git ')) {
      if (currentChunk.length > 0) chunks.push(currentChunk.join('\n'));
      currentChunk = [line];
    } else {
      currentChunk.push(line);
    }
  }
  if (currentChunk.length > 0) chunks.push(currentChunk.join('\n'));

  // Extract DiffFileIdentity for each chunk, then compute canonical keys via
  // the single authority: buildFileKeys from diffFileKey.ts.
  const identities = chunks.map((patch) => extractFileIdentity(patch));
  const canonicalKeys = buildFileKeys(identities);

  return chunks.flatMap((patch, index) => {
    const identity = identities[index];
    const canonicalKey = canonicalKeys[index];
    if (identity === undefined || canonicalKey === undefined) return [];
    const path = extractFilePath(patch) ?? `file-${index}`;
    const lang = path.split('.').pop()?.toUpperCase() ?? '';
    const { additions, deletions } = countChanges(patch);
    return [
      {
        id: `${path}::${index}`,
        path,
        oldFile: identity.oldFile,
        newFile: identity.newFile,
        canonicalKey,
        lang,
        additions,
        deletions,
        patch,
        lineCount: countLines(patch),
      },
    ];
  });
}

function countLines(patch: string): number {
  let count = 1;
  for (let index = 0; index < patch.length; index++) {
    if (patch[index] === '\n') count++;
  }
  return count;
}

/**
 * Extract the canonical file path from a single-file patch chunk.
 *
 * Handles:
 *  - Normal paths:         `diff --git a/foo.ts b/foo.ts`
 *  - Paths with spaces:    git diff quotes them — `diff --git "a/my file.ts" "b/my file.ts"`
 *                          or leaves them unquoted but the `b/` prefix ends at end-of-line
 *  - Renames:              returns the NEW path (b/ side)
 *  - Deletions:            `+++ /dev/null` → falls back to the a/ side from the header
 *  - Fallback:             `+++ b/<path>` line
 */
export function extractFilePath(patch: string): string | null {
  // Quoted form: diff --git "a/..." "b/..."
  const quotedMatch = /^diff --git "a\/(.+)" "b\/(.+)"/m.exec(patch);
  if (quotedMatch !== null) {
    return quotedMatch[2] ?? quotedMatch[1] ?? null;
  }

  // Unquoted form: diff --git a/<oldPath> b/<newPath>
  // The last ` b/` splits paths containing spaces, but embedded ` b/`
  // in a filename remains ambiguous without quoted git headers.
  const headerLineMatch = /^diff --git a\/.+ b\/.+$/m.exec(patch);
  if (headerLineMatch !== null) {
    const headerLine = headerLineMatch[0];
    // Strip the leading `diff --git ` prefix then split on the LAST ` b/`
    const withoutPrefix = headerLine.slice('diff --git '.length);
    const lastBSlash = withoutPrefix.lastIndexOf(' b/');
    if (lastBSlash !== -1) {
      const bPath = withoutPrefix.slice(lastBSlash + 3); // after " b/"
      if (bPath !== '/dev/null' && bPath !== '') return bPath;
      // Deletion: b/ is /dev/null, return the a/ path
      const aPath = withoutPrefix.slice(2, lastBSlash); // after "a/"
      if (aPath !== '') return aPath;
    }
  }

  // Fallback: `+++ b/<path>` (unified diff header without git prefix)
  const plusMatch = /^\+\+\+ b\/(.+)$/m.exec(patch);
  if (plusMatch !== null) {
    const p = plusMatch[1]?.trim() ?? null;
    return p !== null && p !== '' ? p : null;
  }

  return null;
}

function countChanges(patch: string): {
  additions: number;
  deletions: number;
} {
  let additions = 0;
  let deletions = 0;
  for (const line of patch.split('\n')) {
    if (line.startsWith('+++') || line.startsWith('---')) continue;
    if (line.startsWith('+')) additions += 1;
    else if (line.startsWith('-')) deletions += 1;
  }
  return { additions, deletions };
}
